// Generates src/lib/monaco.generated.ts: Monaco's editor.main without the
// LSP client and the TS/CSS/JSON/HTML language services. CodeDiver only needs
// syntax highlighting (Monarch grammars) and editor features (code lenses,
// find, diff editor), which keeps the bundle and worker setup small.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const main = join(root, 'node_modules/monaco-editor/esm/vs/editor/editor.main.js');
const out = join(root, 'src/lib/monaco.generated.ts');
if (!existsSync(main)) {
  console.warn('gen-monaco: monaco-editor not installed, skipping');
  process.exit(0);
}
const lines = readFileSync(main, 'utf8').split('\n');
const imports = [];
for (const line of lines) {
  const m = line.match(/^import '(.+)';$/);
  if (!m) continue;
  const spec = m[1];
  if (spec.includes('languages/features/') || spec.includes('monaco-lsp-client')) continue;
  // Resolve relative to esm/vs/editor and re-root on the @monaco alias.
  const abs = join('editor', spec).replace(/\\/g, '/');
  imports.push(`import '@monaco/${abs}';`);
}
const body = `// Code generated by scripts/gen-monaco.mjs; DO NOT EDIT.
/* eslint-disable */
${imports.join('\n')}
export * from '@monaco/editor/editor.api.js';
`;
writeFileSync(out, body);
console.log(`gen-monaco: wrote ${imports.length} imports to ${out}`);
